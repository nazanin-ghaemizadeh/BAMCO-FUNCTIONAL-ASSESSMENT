 d.querySelector('.assessment-back-action').click();await tick();assert.equal(requests.length,2,'fresh metadata is reused while on the welcome page');
 [...d.querySelectorAll('.gate-card')].find(b=>b.textContent.includes('ارزیابی‌های فعال')).click();
